-- ============================================================================
-- 17_textos_libres.sql — Juntar los contenidos escritos a mano que son el mismo
--
-- Lo que el docente escribe en «¿Trabajás otro que no está en la lista?» se
-- cuenta por su texto normalizado (sin mayúsculas, acentos ni puntuación), así
-- que «Múltiplos y divisores» y «MULTIPLOS Y DIVISORES.» ya suman juntos. Pero
-- «Multiplos y divisiores» o «Criterio de divisibilidad» quedaban aparte, y en
-- el panel aparecían como contenidos distintos con un docente cada uno.
--
-- Esto agrega dos listas que arma el equipo (con un script de
-- sql/mantenimiento/) y las aplica:
--
--   equivalencias_texto_libre  en un saber, una forma escrita (variante) es la
--                              misma que otra (canónico): la respuesta pasa a
--                              decir el canónico. Si el mismo envío ya tenía
--                              el canónico, la variante sobra y se borra.
--   textos_no_trabajo          respuestas que dicen que el saber no se trabaja
--                              («No», «No trabajo estos saberes»): se borran
--                              como contenido y, si en ese envío no queda ningún
--                              otro contenido del saber, el saber pasa a «no
--                              trabajo» (como si hubiera tocado el botón).
--
-- Cómo se aplica:
--   - aplicar_textos_libres() lo aplica a todo lo que ya está cargado;
--   - un trigger lo aplica a cada envío nuevo y a cada reenvío, que si no
--     volvería a traer las formas escritas como el docente las escribió. Si
--     algo falla ahí, el envío entra igual, sin unificar (avisa con un warning).
--
-- Todo cambio queda en textos_libres_cambios, con el texto como estaba, y se
-- puede deshacer:
--   - separar_variante(saber_id, variante) saca una equivalencia y devuelve
--     las respuestas a como las escribió el docente;
--   - restaurar_texto_no(texto) saca un texto de la lista de «no trabajo» y
--     vuelve a poner esas respuestas como contenido.
--   Una respuesta borrada vuelve solo si el docente no reenvió esa materia
--   después: si reenvió, vale lo nuevo.
--
-- Se corre desde el SQL Editor. Nadie lo puede llamar desde la API: no hay
-- pantalla en el panel para esto («Lo que NO va» en CLAUDE.md).
--
-- Se puede correr más de una vez.
-- ============================================================================


create table if not exists public.equivalencias_texto_libre (
  saber_id    text not null references public.saberes (id),
  variante    text not null,   -- texto normalizado, como lo escribió alguien
  canonico    text not null,   -- texto normalizado con el que se junta
  texto       text not null,   -- cómo se muestra el canónico
  tipo        text not null default 'escritura'
              check (tipo in ('escritura', 'notacion')),
  creado_en   timestamptz not null default now(),
  primary key (saber_id, variante),
  check (variante <> canonico),
  check (canonico = public.normalizar_texto(texto))
);

create table if not exists public.textos_no_trabajo (
  texto_normalizado  text primary key,
  creado_en          timestamptz not null default now()
);

-- Sin claves foráneas a selecciones ni aportes: un reenvío borra las
-- selecciones, y lo anotado tiene que quedar igual para poder deshacer.
create table if not exists public.textos_libres_cambios (
  id                       bigint generated by default as identity primary key,
  hecho_en                 timestamptz not null default now(),
  accion                   text not null check (accion in ('unificado', 'repetido', 'no_trabajo')),
  seleccion_id             bigint not null,
  aporte_id                bigint not null,
  -- El del aporte en ese momento: si después cambió, el docente reenvió.
  enviado_en               timestamptz,
  saber_id                 text not null,
  tipo                     text not null,
  contenido_sugerido_id    text,
  texto                    text not null,   -- como estaba
  texto_normalizado        text not null,   -- como estaba
  orden                    smallint not null,
  texto_nuevo              text,            -- 'unificado': cómo quedó
  texto_normalizado_nuevo  text,
  agrego_no_trabajado      boolean not null default false,
  deshecho_en              timestamptz
);
create index if not exists textos_libres_cambios_texto_idx
  on public.textos_libres_cambios (texto_normalizado, saber_id) where deshecho_en is null;

alter table public.equivalencias_texto_libre enable row level security;
alter table public.textos_no_trabajo         enable row level security;
alter table public.textos_libres_cambios     enable row level security;
revoke all on public.equivalencias_texto_libre from anon, authenticated;
revoke all on public.textos_no_trabajo         from anon, authenticated;
revoke all on public.textos_libres_cambios     from anon, authenticated;


-- ----------------------------------------------------------------------------
-- aplicar_textos_libres(p_aportes) — aplica las dos listas
--
-- Con p_aportes en null, a todo lo cargado; si no, solo a esos envíos (lo usa
-- el trigger). Devuelve cuántas respuestas cambió.
-- ----------------------------------------------------------------------------

create or replace function public.aplicar_textos_libres(p_aportes bigint[] default null)
returns jsonb
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_desde bigint;
begin
  select coalesce(max(id), 0) into v_desde from public.textos_libres_cambios;

  -- «No trabajo»: se borra la respuesta, y el saber pasa a no trabajado si
  -- en ese envío no queda ningún otro contenido suyo (si queda, ganan los
  -- contenidos, como en registrar_aporte).
  with cand as (
    select s.id, s.aporte_id, s.saber_id, s.tipo, s.contenido_sugerido_id,
           s.texto, s.texto_normalizado, s.orden
      from public.selecciones s
      join public.textos_no_trabajo t on t.texto_normalizado = s.texto_normalizado
     where s.tipo = 'libre'
       and (p_aportes is null or s.aporte_id = any (p_aportes))
  ),
  sin_otro as (
    select distinct c.aporte_id, c.saber_id
      from cand c
     where not exists (
       select 1 from public.selecciones x
        where x.aporte_id = c.aporte_id
          and x.saber_id  = c.saber_id
          and x.id not in (select id from cand)
     )
  ),
  borradas as (
    delete from public.selecciones s
     using cand c
     where s.id = c.id
    returning s.id
  ),
  agregados as (
    insert into public.saberes_no_trabajados (aporte_id, saber_id)
    select aporte_id, saber_id from sin_otro
    on conflict do nothing
    returning aporte_id, saber_id
  )
  insert into public.textos_libres_cambios
    (accion, seleccion_id, aporte_id, enviado_en, saber_id, tipo, contenido_sugerido_id,
     texto, texto_normalizado, orden, agrego_no_trabajado)
  select 'no_trabajo', c.id, c.aporte_id, a.enviado_en, c.saber_id, c.tipo, c.contenido_sugerido_id,
         c.texto, c.texto_normalizado, c.orden,
         exists (select 1 from agregados g where g.aporte_id = c.aporte_id and g.saber_id = c.saber_id)
    from cand c
    join public.aportes a on a.id = c.aporte_id
   where c.id in (select id from borradas);

  -- Equivalencias: la variante pasa a decir el canónico. Si el envío ya lo
  -- tiene (o tiene dos variantes del mismo), sobra y se borra. Si el canónico
  -- es una sugerencia del saber, cuenta como del catálogo (como en
  -- registrar_aporte).
  with cand as (
    select s.id, s.aporte_id, s.saber_id, s.tipo, s.contenido_sugerido_id,
           s.texto, s.texto_normalizado, s.orden,
           e.canonico, coalesce(cs.texto, e.texto) as texto_canonico, cs.id as sugerencia_id
      from public.selecciones s
      join public.equivalencias_texto_libre e
        on e.saber_id = s.saber_id and e.variante = s.texto_normalizado
      left join lateral (
        select c.id, c.texto
          from public.contenidos_sugeridos c
         where c.saber_id = s.saber_id
           and c.texto_normalizado = e.canonico
         limit 1
      ) cs on true
     where s.tipo = 'libre'
       and (p_aportes is null or s.aporte_id = any (p_aportes))
  ),
  marcadas as (
    select c.*,
           exists (select 1 from public.selecciones x
                    where x.aporte_id = c.aporte_id
                      and x.saber_id  = c.saber_id
                      and x.texto_normalizado = c.canonico)
           or row_number() over (partition by c.aporte_id, c.saber_id, c.canonico
                                 order by c.orden, c.id) > 1 as sobra
      from cand c
  ),
  borradas as (
    delete from public.selecciones s
     using marcadas m
     where s.id = m.id and m.sobra
    returning s.id
  ),
  cambiadas as (
    update public.selecciones s
       set texto = m.texto_canonico,
           texto_normalizado = m.canonico,
           tipo = case when m.sugerencia_id is null then 'libre' else 'catalogo' end,
           contenido_sugerido_id = m.sugerencia_id
      from marcadas m
     where s.id = m.id and not m.sobra
    returning s.id
  )
  insert into public.textos_libres_cambios
    (accion, seleccion_id, aporte_id, enviado_en, saber_id, tipo, contenido_sugerido_id,
     texto, texto_normalizado, orden, texto_nuevo, texto_normalizado_nuevo)
  select case when m.sobra then 'repetido' else 'unificado' end,
         m.id, m.aporte_id, a.enviado_en, m.saber_id, m.tipo, m.contenido_sugerido_id,
         m.texto, m.texto_normalizado, m.orden,
         case when not m.sobra then m.texto_canonico end,
         case when not m.sobra then m.canonico end
    from marcadas m
    join public.aportes a on a.id = m.aporte_id
   where m.id in (select id from borradas)
      or m.id in (select id from cambiadas);

  return (
    select jsonb_build_object(
             'unificadas',            count(*) filter (where accion = 'unificado'),
             'repetidas_borradas',    count(*) filter (where accion = 'repetido'),
             'no_trabajo_borradas',   count(*) filter (where accion = 'no_trabajo'),
             'saberes_no_trabajados', count(distinct (aporte_id, saber_id))
                                        filter (where agrego_no_trabajado))
      from public.textos_libres_cambios
     where id > v_desde
  );
end;
$$;


-- ----------------------------------------------------------------------------
-- Cada envío nuevo (y cada reenvío) pasa por las mismas listas
--
-- registrar_aporte() inserta todas las selecciones de un envío en una sola
-- sentencia; al terminar, este trigger las revisa. Si algo falla, el envío
-- entra igual: unificar no puede ser motivo para perder una carga.
-- ----------------------------------------------------------------------------

create or replace function public.aplicar_textos_libres_al_enviar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_aportes bigint[];
begin
  select array_agg(distinct n.aporte_id) into v_aportes
    from nuevas n
   where n.tipo = 'libre';
  if v_aportes is not null then
    begin
      perform public.aplicar_textos_libres(v_aportes);
    exception when others then
      raise warning 'No se pudieron unificar los textos escritos a mano del envío: %', sqlerrm;
    end;
  end if;
  return null;
end;
$$;

drop trigger if exists aplicar_textos_libres on public.selecciones;
create trigger aplicar_textos_libres
  after insert on public.selecciones
  referencing new table as nuevas
  for each statement
  execute function public.aplicar_textos_libres_al_enviar();

-- Si el trigger ya pasó un saber a «no trabajo» y el mismo envío también lo
-- traía marcado con el botón, registrar_aporte() lo insertaría dos veces y el
-- envío fallaría por la clave. Lo repetido no se inserta.
create or replace function public.no_repetir_no_trabajado()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if exists (select 1 from public.saberes_no_trabajados n
              where n.aporte_id = new.aporte_id and n.saber_id = new.saber_id) then
    return null;
  end if;
  return new;
end;
$$;

drop trigger if exists no_repetir_no_trabajado on public.saberes_no_trabajados;
create trigger no_repetir_no_trabajado
  before insert on public.saberes_no_trabajados
  for each row
  execute function public.no_repetir_no_trabajado();


-- ----------------------------------------------------------------------------
-- separar_variante(saber_id, variante) — deshace una equivalencia
--
-- Saca la equivalencia (así no se vuelve a aplicar) y devuelve las respuestas
-- a como las escribió el docente. La variante se puede pasar como la escribió
-- o ya normalizada.
-- ----------------------------------------------------------------------------

create or replace function public.separar_variante(p_saber_id text, p_variante text)
returns jsonb
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_variante text := public.normalizar_texto(p_variante);
  v_vueltas  integer;
  v_repuestas integer;
begin
  delete from public.equivalencias_texto_libre
   where saber_id = p_saber_id and variante = v_variante;

  with vueltas as (
    update public.selecciones s
       set texto = l.texto,
           texto_normalizado = l.texto_normalizado,
           tipo = l.tipo,
           contenido_sugerido_id = l.contenido_sugerido_id
      from public.textos_libres_cambios l
     where l.accion = 'unificado'
       and l.deshecho_en is null
       and l.saber_id = p_saber_id
       and l.texto_normalizado = v_variante
       and s.id = l.seleccion_id
       and s.texto_normalizado = l.texto_normalizado_nuevo
    returning s.id
  )
  select count(*) into v_vueltas from vueltas;

  insert into public.selecciones
    (aporte_id, saber_id, tipo, contenido_sugerido_id, texto, texto_normalizado, orden)
  select l.aporte_id, l.saber_id, l.tipo, l.contenido_sugerido_id, l.texto, l.texto_normalizado, l.orden
    from public.textos_libres_cambios l
    join public.aportes a on a.id = l.aporte_id and a.enviado_en = l.enviado_en
   where l.accion = 'repetido'
     and l.deshecho_en is null
     and l.saber_id = p_saber_id
     and l.texto_normalizado = v_variante
  on conflict do nothing;
  get diagnostics v_repuestas = row_count;

  update public.textos_libres_cambios
     set deshecho_en = now()
   where accion in ('unificado', 'repetido')
     and deshecho_en is null
     and saber_id = p_saber_id
     and texto_normalizado = v_variante;

  return jsonb_build_object('vuelven_a_su_texto', v_vueltas, 'repuestas', v_repuestas);
end;
$$;


-- ----------------------------------------------------------------------------
-- restaurar_texto_no(texto) — deshace un texto de «no trabajo»
--
-- Lo saca de la lista y vuelve a poner esas respuestas como contenido. El
-- saber deja de estar en «no trabajo» en esos envíos, porque ahora tiene un
-- contenido (ganan los contenidos, como en registrar_aporte).
-- ----------------------------------------------------------------------------

create or replace function public.restaurar_texto_no(p_texto text)
returns jsonb
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_texto     text := public.normalizar_texto(p_texto);
  v_repuestas integer;
  v_saberes   integer;
begin
  delete from public.textos_no_trabajo where texto_normalizado = v_texto;

  with repuestas as (
    insert into public.selecciones
      (aporte_id, saber_id, tipo, contenido_sugerido_id, texto, texto_normalizado, orden)
    select l.aporte_id, l.saber_id, l.tipo, l.contenido_sugerido_id, l.texto, l.texto_normalizado, l.orden
      from public.textos_libres_cambios l
      join public.aportes a on a.id = l.aporte_id and a.enviado_en = l.enviado_en
     where l.accion = 'no_trabajo'
       and l.deshecho_en is null
       and l.texto_normalizado = v_texto
    on conflict do nothing
    returning aporte_id, saber_id
  ),
  quitados as (
    delete from public.saberes_no_trabajados n
     using (select distinct aporte_id, saber_id from repuestas) r
     where n.aporte_id = r.aporte_id and n.saber_id = r.saber_id
    returning 1
  )
  select (select count(*) from repuestas), (select count(*) from quitados)
    into v_repuestas, v_saberes;

  update public.textos_libres_cambios
     set deshecho_en = now()
   where accion = 'no_trabajo'
     and deshecho_en is null
     and texto_normalizado = v_texto;

  return jsonb_build_object('repuestas', v_repuestas, 'saberes_que_dejan_de_ser_no_trabajados', v_saberes);
end;
$$;


revoke execute on function public.aplicar_textos_libres(bigint[])       from public, anon, authenticated;
revoke execute on function public.aplicar_textos_libres_al_enviar()     from public, anon, authenticated;
revoke execute on function public.no_repetir_no_trabajado()             from public, anon, authenticated;
revoke execute on function public.separar_variante(text, text)          from public, anon, authenticated;
revoke execute on function public.restaurar_texto_no(text)              from public, anon, authenticated;

-- Si llegó hasta acá, quedó instalado: muestra cuántas equivalencias hay
select count(*) as equivalencias from public.equivalencias_texto_libre;
