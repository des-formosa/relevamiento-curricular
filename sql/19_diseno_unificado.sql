-- ============================================================================
-- 19_diseno_unificado.sql — Cerrar el diseño curricular unificado
--
-- Lo pidió el equipo técnico el 12/11/2026, con la carga terminada: «que la
-- página pueda cerrar el diseño curricular completo» y entregarlo, con una
-- carátula y el marco argumentativo, y que el equipo lo pueda editar antes.
--
-- Cómo funciona:
--
-- 1. diseno_propuesta(materia, año) cuenta lo que cargaron los docentes en un
--    año de una materia (en las artísticas, año 0: todo el ciclo, porque el
--    diseño no las diferencia por año): cuántos informaron cada saber, cuántos
--    lo trabajan, cuántos no, y cuántos eligieron cada contenido. Con eso el
--    panel arma la primera propuesta: los saberes de más acuerdo quedan como
--    prioritarios, los de poco acuerdo marcados «a revisar», los contenidos
--    ordenados de más a menos elegidos.
-- 2. En cuanto el equipo toca algo, ese año de esa materia queda guardado en
--    diseno_materias (una foto de la propuesta, ya editada). Desde ahí se edita
--    sobre la foto: las cargas que lleguen después no la cambian, salvo que el
--    equipo pida «volver a armarla desde las cargas» (queda la anterior en
--    diseno_versiones).
-- 3. Cada año de cada materia se cierra cuando el equipo terminó de revisarlo.
--    Cerrado, no se puede cambiar hasta reabrirlo.
-- 4. La carátula, el marco argumentativo y las opciones del documento son uno
--    solo (diseno_documento); la presentación de cada materia, opcional, va en
--    diseno_presentaciones.
--
-- Nada de esto toca el catálogo ni lo que ven los docentes en el formulario.
-- Todo se escribe por funciones security definer que verifican es_equipo();
-- las tablas las lee solo el equipo.
--
-- Se puede correr más de una vez.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Tablas
-- ----------------------------------------------------------------------------

-- La carátula, el marco argumentativo y las opciones del documento: una fila
create table if not exists public.diseno_documento (
  id              smallint primary key default 1 check (id = 1),
  datos           jsonb not null default '{}'::jsonb,
  actualizado_por uuid references auth.users (id) on delete set null,
  actualizado_en  timestamptz not null default now()
);

-- Un año de una materia, como lo dejó el equipo. anio = 0: todo el ciclo
-- (Música, Danza, Teatro y Artes Visuales, que no diferencian saberes por año).
--   datos = { base: { docentes, escuelas, cargas, armada_en, criterios },
--             saberes: [{ id, eje_id, trimestre, texto, estado, …, contenidos: [...] }] }
create table if not exists public.diseno_materias (
  espacio_id      text not null references public.espacios_curriculares (id),
  anio            smallint not null check (anio between 0 and 3),
  datos           jsonb not null,
  estado          text not null default 'en_revision' check (estado in ('en_revision', 'cerrada')),
  cerrada_por     uuid references auth.users (id) on delete set null,
  cerrada_en      timestamptz,
  actualizada_por uuid references auth.users (id) on delete set null,
  actualizada_en  timestamptz not null default now(),
  primary key (espacio_id, anio)
);

-- Lo que había antes de volver a armar una materia desde las cargas, o al
-- cerrarla: por si hay que recuperar algo. No tiene pantalla; se consulta en
-- el SQL Editor.
create table if not exists public.diseno_versiones (
  id          bigint generated by default as identity primary key,
  espacio_id  text not null,
  anio        smallint not null,
  datos       jsonb not null,
  motivo      text not null check (motivo in ('volver_a_armar', 'cerrada')),
  guardada_por uuid references auth.users (id) on delete set null,
  guardada_en  timestamptz not null default now()
);
create index if not exists diseno_versiones_materia_idx on public.diseno_versiones (espacio_id, anio, guardada_en desc);

-- La presentación de cada materia, si el equipo la escribe. Va antes de sus saberes.
create table if not exists public.diseno_presentaciones (
  espacio_id      text primary key references public.espacios_curriculares (id),
  texto           text not null default '',
  actualizada_por uuid references auth.users (id) on delete set null,
  actualizada_en  timestamptz not null default now()
);

alter table public.diseno_documento      enable row level security;
alter table public.diseno_materias       enable row level security;
alter table public.diseno_versiones      enable row level security;
alter table public.diseno_presentaciones enable row level security;

do $$
declare t text;
begin
  foreach t in array array['diseno_documento', 'diseno_materias', 'diseno_versiones', 'diseno_presentaciones'] loop
    execute format('drop policy if exists "equipo lee" on public.%I', t);
    execute format('create policy "equipo lee" on public.%I for select to authenticated using ((select public.es_equipo()))', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('revoke insert, update, delete on public.%I from authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
  end loop;
end $$;


-- ----------------------------------------------------------------------------
-- 2. diseno_propuesta(materia, año)
--
-- Lo que cargaron los docentes en un año de una materia, para armar la
-- propuesta. Año 0: todos los años juntos (las artísticas). Solo envíos reales
-- y solo saberes activos que el docente ve (calidad distinta de 'mala').
--
-- Devuelve { base: { docentes, escuelas, cargas },
--            saberes: [{ id, eje_id, trimestre, orden, texto,
--                        informan, trabajan, no_trabajan,
--                        contenidos: [{ texto, tipo, contenido_sugerido_id, docentes }] }] }
-- Los contenidos traen también las sugerencias del catálogo que nadie eligió
-- (docentes = 0), para que el equipo pueda sumarlas.
-- ----------------------------------------------------------------------------

create or replace function public.diseno_propuesta(p_espacio_id text, p_anio smallint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_resultado jsonb;
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede ver el diseño unificado.');
  end if;

  with ap as (
    select a.id, a.docente_id, a.escuela_id
      from public.aportes a
     where a.espacio_id = p_espacio_id
       and a.es_ejemplo = false
       and (coalesce(p_anio, 0) = 0 or a.anio = p_anio)
  ),
  sab as (
    select s.id, s.eje_id, s.trimestre, s.orden, s.texto, ej.orden as eje_orden
      from public.saberes s
      join public.ejes ej on ej.id = s.eje_id
     where ej.espacio_id = p_espacio_id
       and s.estado = 'activo'
       and s.calidad <> 'mala'
       and (case when coalesce(p_anio, 0) = 0 then s.anio is null else (s.anio is null or s.anio = p_anio) end)
  ),
  sel as (
    select se.aporte_id, se.saber_id, se.tipo, se.contenido_sugerido_id, se.texto, se.texto_normalizado
      from public.selecciones se
      join ap on ap.id = se.aporte_id
     where se.saber_id in (select id from sab)
  ),
  trabajan as (
    select saber_id, count(distinct aporte_id) as n from sel group by saber_id
  ),
  no_trabajan as (
    select n.saber_id, count(distinct n.aporte_id) as n
      from public.saberes_no_trabajados n
      join ap on ap.id = n.aporte_id
     where n.saber_id in (select id from sab)
       -- el que eligió contenidos y además tocó «no trabajo» cuenta como que lo trabaja
       and not exists (select 1 from sel where sel.aporte_id = n.aporte_id and sel.saber_id = n.saber_id)
     group by n.saber_id
  ),
  elegidos as (
    select saber_id, texto_normalizado,
           mode() within group (order by texto) as texto,
           bool_or(tipo = 'catalogo')           as es_catalogo,
           max(contenido_sugerido_id)           as contenido_sugerido_id,
           count(distinct aporte_id)            as n
      from sel
     group by saber_id, texto_normalizado
  ),
  -- Las sugerencias del catálogo que nadie eligió
  sin_elegir as (
    select c.saber_id, c.texto_normalizado, c.texto, true as es_catalogo, c.id as contenido_sugerido_id, 0::bigint as n
      from public.contenidos_sugeridos c
     where c.saber_id in (select id from sab)
       and c.estado = 'activo'
       and not exists (select 1 from elegidos e where e.saber_id = c.saber_id and e.texto_normalizado = c.texto_normalizado)
  ),
  todos as (
    select * from elegidos union all select * from sin_elegir
  ),
  contenidos as (
    select saber_id,
           jsonb_agg(jsonb_build_object(
                       'texto', texto,
                       'tipo', case when es_catalogo then 'catalogo' else 'libre' end,
                       'contenido_sugerido_id', contenido_sugerido_id,
                       'docentes', n)
                     order by n desc, es_catalogo desc, texto) as lista
      from todos
     group by saber_id
  )
  select jsonb_build_object(
    'base', (select jsonb_build_object('docentes', count(distinct docente_id),
                                       'escuelas', count(distinct escuela_id),
                                       'cargas',   count(*)) from ap),
    'saberes', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', s.id, 'eje_id', s.eje_id, 'trimestre', s.trimestre, 'orden', s.orden, 'texto', s.texto,
               'informan', coalesce(t.n, 0) + coalesce(nt.n, 0),
               'trabajan', coalesce(t.n, 0),
               'no_trabajan', coalesce(nt.n, 0),
               'contenidos', coalesce(c.lista, '[]'::jsonb))
             order by s.trimestre, s.orden, s.eje_orden, s.id)
        from sab s
        left join trabajan t     on t.saber_id = s.id
        left join no_trabajan nt on nt.saber_id = s.id
        left join contenidos c   on c.saber_id = s.id
    ), '[]'::jsonb)
  ) into v_resultado;

  return v_resultado;
end;
$$;


-- ----------------------------------------------------------------------------
-- 3. diseno_estado()
--
-- Cómo va el cierre: un renglón por año de materia que el equipo ya tocó, con
-- quién y cuándo, y los números de todo el relevamiento para la carátula y el
-- marco (docentes, escuelas, cargas reales).
-- ----------------------------------------------------------------------------

create or replace function public.diseno_estado()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select case when not public.es_equipo() then jsonb_build_object('error', 'Tu usuario no puede ver el diseño unificado.') else
    jsonb_build_object(
      'materias', coalesce((
        select jsonb_agg(jsonb_build_object(
                 'espacio_id', m.espacio_id, 'anio', m.anio, 'estado', m.estado,
                 'actualizada_en', m.actualizada_en,
                 'actualizada_por', coalesce(nullif(btrim(ea.nombre), ''), 'alguien del equipo'),
                 'cerrada_en', m.cerrada_en,
                 'cerrada_por', case when m.cerrada_en is null then null else coalesce(nullif(btrim(ec.nombre), ''), 'alguien del equipo') end)
               order by m.espacio_id, m.anio)
          from public.diseno_materias m
          left join public.equipo_planificacion ea on ea.usuario_id = m.actualizada_por
          left join public.equipo_planificacion ec on ec.usuario_id = m.cerrada_por
      ), '[]'::jsonb),
      'relevamiento', (
        select jsonb_build_object('docentes', count(distinct a.docente_id),
                                  'escuelas', count(distinct a.escuela_id),
                                  'cargas',   count(*))
          from public.aportes a where a.es_ejemplo = false
      ),
      'documento', (
        select jsonb_build_object('datos', d.datos, 'actualizado_en', d.actualizado_en,
                                  'actualizado_por', coalesce(nullif(btrim(e.nombre), ''), 'alguien del equipo'))
          from public.diseno_documento d
          left join public.equipo_planificacion e on e.usuario_id = d.actualizado_por
         where d.id = 1
      ),
      'presentaciones', coalesce((
        select jsonb_object_agg(espacio_id, texto) from public.diseno_presentaciones where btrim(texto) <> ''
      ), '{}'::jsonb)
    )
  end;
$$;


-- ----------------------------------------------------------------------------
-- 4. guardar_diseno_materia(materia, año, datos, versión)
--
-- Guarda un año de una materia. versión = actualizada_en de lo que se tenía
-- abierto (null si se empieza de la propuesta): si otra persona guardó en el
-- medio, no se pisa y lo dice. Cerrada, no se cambia.
-- ----------------------------------------------------------------------------

create or replace function public.guardar_diseno_materia(p_espacio_id text, p_anio smallint, p_datos jsonb, p_version timestamptz default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fila public.diseno_materias;
  v_esp  public.espacios_curriculares;
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede editar el diseño unificado.');
  end if;
  select * into v_esp from public.espacios_curriculares where id = p_espacio_id;
  if not found then
    return jsonb_build_object('error', 'Esa materia no está en el catálogo.');
  end if;
  if v_esp.saberes_por_ciclo and p_anio <> 0 or not v_esp.saberes_por_ciclo and not (p_anio = any (v_esp.anios_dictados)) then
    return jsonb_build_object('error', 'Esa materia no se dicta en ese año.');
  end if;
  if p_datos is null or jsonb_typeof(p_datos->'saberes') is distinct from 'array' then
    return jsonb_build_object('error', 'No llegó la lista de saberes. Volvé a intentar.');
  end if;

  select * into v_fila from public.diseno_materias where espacio_id = p_espacio_id and anio = p_anio for update;
  if found then
    if v_fila.estado = 'cerrada' then
      return jsonb_build_object('error', 'Este año ya está cerrado. Para cambiarlo, primero reabrilo.', 'conflicto', true);
    end if;
    if p_version is null or date_trunc('milliseconds', v_fila.actualizada_en) <> date_trunc('milliseconds', p_version) then
      return jsonb_build_object('error', 'Otra persona del equipo cambió este año mientras lo tenías abierto. Traé su versión para seguir sobre lo último.',
                                'conflicto', true);
    end if;
    update public.diseno_materias
       set datos = p_datos, actualizada_por = (select auth.uid()), actualizada_en = clock_timestamp()
     where espacio_id = p_espacio_id and anio = p_anio
    returning * into v_fila;
  else
    if p_version is not null then
      return jsonb_build_object('error', 'Otra persona del equipo volvió a armar este año desde las cargas. Traé la versión nueva para seguir.',
                                'conflicto', true);
    end if;
    insert into public.diseno_materias (espacio_id, anio, datos, actualizada_por, actualizada_en)
    values (p_espacio_id, p_anio, p_datos, (select auth.uid()), clock_timestamp())
    returning * into v_fila;
  end if;
  return jsonb_build_object('estado', v_fila.estado, 'actualizada_en', v_fila.actualizada_en);
end;
$$;


-- ----------------------------------------------------------------------------
-- 5. cerrar_diseno_materia(materia, año, cerrar, versión)
--
-- Cerrar exige que no quede ningún saber «a revisar» y que quede al menos uno
-- en el diseño. Reabrir no pide nada. Al cerrar, queda una copia en
-- diseno_versiones.
-- ----------------------------------------------------------------------------

create or replace function public.cerrar_diseno_materia(p_espacio_id text, p_anio smallint, p_cerrar boolean, p_version timestamptz default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fila    public.diseno_materias;
  v_revisar integer;
  v_quedan  integer;
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede editar el diseño unificado.');
  end if;
  select * into v_fila from public.diseno_materias where espacio_id = p_espacio_id and anio = p_anio for update;
  if not found then
    return jsonb_build_object('error', 'Este año todavía no tiene cambios guardados. Revisalo antes de cerrarlo.');
  end if;
  if p_version is not null and date_trunc('milliseconds', v_fila.actualizada_en) <> date_trunc('milliseconds', p_version) then
    return jsonb_build_object('error', 'Otra persona del equipo cambió este año mientras lo tenías abierto. Traé su versión antes de cerrarlo.',
                              'conflicto', true);
  end if;

  if p_cerrar then
    if v_fila.estado = 'cerrada' then
      return jsonb_build_object('estado', v_fila.estado, 'actualizada_en', v_fila.actualizada_en);
    end if;
    select count(*) filter (where s->>'estado' = 'revisar'),
           count(*) filter (where s->>'estado' = 'prioritario')
      into v_revisar, v_quedan
      from jsonb_array_elements(v_fila.datos->'saberes') s;
    if v_revisar > 0 then
      return jsonb_build_object('error', case when v_revisar = 1
        then 'Queda 1 saber para revisar: decidí si queda en el diseño o sale, y después cerrá el año.'
        else format('Quedan %s saberes para revisar: decidí si cada uno queda en el diseño o sale, y después cerrá el año.', v_revisar) end);
    end if;
    if v_quedan = 0 then
      return jsonb_build_object('error', 'No queda ningún saber en el diseño de este año. Dejá al menos uno antes de cerrarlo.');
    end if;
    update public.diseno_materias
       set estado = 'cerrada', cerrada_por = (select auth.uid()), cerrada_en = clock_timestamp(), actualizada_en = clock_timestamp()
     where espacio_id = p_espacio_id and anio = p_anio
    returning * into v_fila;
    insert into public.diseno_versiones (espacio_id, anio, datos, motivo, guardada_por)
    values (p_espacio_id, p_anio, v_fila.datos, 'cerrada', (select auth.uid()));
  else
    update public.diseno_materias
       set estado = 'en_revision', cerrada_por = null, cerrada_en = null, actualizada_en = clock_timestamp()
     where espacio_id = p_espacio_id and anio = p_anio
    returning * into v_fila;
  end if;
  return jsonb_build_object('estado', v_fila.estado, 'actualizada_en', v_fila.actualizada_en);
end;
$$;


-- ----------------------------------------------------------------------------
-- 6. volver_a_armar_diseno(materia, año)
--
-- Descarta lo editado en ese año y vuelve a la propuesta que sale de las
-- cargas. Lo que había queda en diseno_versiones. Cerrado, no se puede.
-- ----------------------------------------------------------------------------

create or replace function public.volver_a_armar_diseno(p_espacio_id text, p_anio smallint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fila public.diseno_materias;
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede editar el diseño unificado.');
  end if;
  select * into v_fila from public.diseno_materias where espacio_id = p_espacio_id and anio = p_anio for update;
  if not found then
    return jsonb_build_object('ok', true);
  end if;
  if v_fila.estado = 'cerrada' then
    return jsonb_build_object('error', 'Este año está cerrado. Para volver a armarlo, primero reabrilo.');
  end if;
  insert into public.diseno_versiones (espacio_id, anio, datos, motivo, guardada_por)
  values (p_espacio_id, p_anio, v_fila.datos, 'volver_a_armar', (select auth.uid()));
  delete from public.diseno_materias where espacio_id = p_espacio_id and anio = p_anio;
  return jsonb_build_object('ok', true);
end;
$$;


-- ----------------------------------------------------------------------------
-- 7. guardar_diseno_documento(datos, versión) y guardar_presentacion(materia, texto)
-- ----------------------------------------------------------------------------

create or replace function public.guardar_diseno_documento(p_datos jsonb, p_version timestamptz default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fila public.diseno_documento;
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede editar el diseño unificado.');
  end if;
  if p_datos is null or jsonb_typeof(p_datos) <> 'object' then
    return jsonb_build_object('error', 'No llegaron los datos del documento. Volvé a intentar.');
  end if;
  if octet_length(p_datos::text) > 2000000 then
    return jsonb_build_object('error', 'El documento es demasiado pesado (¿una imagen muy grande?). Sacá la imagen o usá una más liviana.');
  end if;
  select * into v_fila from public.diseno_documento where id = 1 for update;
  if found then
    if p_version is null or date_trunc('milliseconds', v_fila.actualizado_en) <> date_trunc('milliseconds', p_version) then
      return jsonb_build_object('error', 'Otra persona del equipo cambió la carátula o el marco mientras los tenías abiertos. Traé su versión para seguir sobre lo último.',
                                'conflicto', true);
    end if;
    update public.diseno_documento
       set datos = p_datos, actualizado_por = (select auth.uid()), actualizado_en = clock_timestamp()
     where id = 1
    returning * into v_fila;
  else
    insert into public.diseno_documento (id, datos, actualizado_por, actualizado_en)
    values (1, p_datos, (select auth.uid()), clock_timestamp())
    returning * into v_fila;
  end if;
  return jsonb_build_object('actualizado_en', v_fila.actualizado_en);
end;
$$;

create or replace function public.guardar_presentacion(p_espacio_id text, p_texto text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede editar el diseño unificado.');
  end if;
  if not exists (select 1 from public.espacios_curriculares where id = p_espacio_id) then
    return jsonb_build_object('error', 'Esa materia no está en el catálogo.');
  end if;
  insert into public.diseno_presentaciones (espacio_id, texto, actualizada_por, actualizada_en)
  values (p_espacio_id, coalesce(p_texto, ''), (select auth.uid()), clock_timestamp())
  on conflict (espacio_id) do update
     set texto = excluded.texto, actualizada_por = excluded.actualizada_por, actualizada_en = excluded.actualizada_en;
  return jsonb_build_object('ok', true);
end;
$$;


