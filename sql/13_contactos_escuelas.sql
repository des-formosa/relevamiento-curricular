-- ============================================================================
-- 13_contactos_escuelas.sql — A quién llamar en cada escuela
--
-- Para el seguimiento de la carga: el equipo ve el contacto de cada escuela
-- (director, celular, correo) al pasar por su nombre, y puede agregar,
-- corregir o quitar uno. Son datos personales, así que:
--   - viven solo acá, nunca en el repositorio (que es público);
--   - los lee el equipo y nadie más (RLS, igual que los aportes);
--   - se escriben solo por guardar_contacto() y quitar_contacto().
--
-- La carga inicial sale de las planillas de directivos con
-- datos/generar_contactos.py, que escribe un SQL aparte que no se versiona.
--
-- Se puede correr más de una vez.
-- ============================================================================


create table if not exists public.contactos_escuela (
  id               bigint generated by default as identity primary key,
  escuela_id       text not null references public.escuelas (id),
  nombre           text check (char_length(btrim(nombre)) between 1 and 120),
  cargo            text check (char_length(btrim(cargo)) between 1 and 80),
  -- Solo dígitos: el panel lo muestra con espacios y arma el enlace de WhatsApp
  celular          text check (celular ~ '^[0-9]{6,15}$'),
  correo           text check (correo ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  -- 'planilla_directivos' = vino de la carga inicial; 'panel' = lo escribió el
  -- equipo. Volver a cargar la planilla reemplaza solo lo primero.
  origen           text not null default 'panel' check (origen in ('planilla_directivos', 'panel')),
  actualizado_por  uuid references auth.users (id) on delete set null,
  actualizado_en   timestamptz not null default now(),
  -- Un contacto sin nada no sirve
  check (nombre is not null or celular is not null or correo is not null)
);

create index if not exists contactos_escuela_idx on public.contactos_escuela (escuela_id);

alter table public.contactos_escuela enable row level security;
revoke all on public.contactos_escuela from anon, authenticated;
grant select on public.contactos_escuela to authenticated;

drop policy if exists "equipo lee" on public.contactos_escuela;
create policy "equipo lee" on public.contactos_escuela
  for select to authenticated using ((select public.es_equipo()));


-- ----------------------------------------------------------------------------
-- guardar_contacto(...) — agrega (p_id null) o corrige uno
--
--   supabase.rpc('guardar_contacto', { p_id: null, p_escuela_id: 'epes-2',
--     p_nombre: 'Ana Pérez', p_cargo: 'Dirección', p_celular: '3704 123456', p_correo: null })
--
-- Los campos vacíos quedan en null. El celular se guarda sin espacios ni
-- guiones. Devuelve el contacto como quedó, o { error } con un mensaje para
-- mostrar tal cual.
-- ----------------------------------------------------------------------------

create or replace function public.guardar_contacto(
  p_id          bigint,
  p_escuela_id  text,
  p_nombre      text,
  p_cargo       text,
  p_celular     text,
  p_correo      text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_nombre  text := nullif(btrim(coalesce(p_nombre, '')), '');
  v_cargo   text := nullif(btrim(coalesce(p_cargo, '')), '');
  v_celular text := nullif(regexp_replace(coalesce(p_celular, ''), '\D', '', 'g'), '');
  v_correo  text := nullif(lower(btrim(coalesce(p_correo, ''))), '');
  v_fila    public.contactos_escuela;
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede cambiar contactos.');
  end if;
  if v_nombre is null and v_celular is null and v_correo is null then
    return jsonb_build_object('error', 'Escribí al menos el celular o el correo.');
  end if;
  if v_celular is not null and char_length(v_celular) not between 6 and 15 then
    return jsonb_build_object('error', 'El celular tiene que tener entre 6 y 15 números, con la característica (por ejemplo 3704 123456).');
  end if;
  if v_correo is not null and v_correo !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    return jsonb_build_object('error', 'El correo no parece completo: tiene que tener una @ y un punto (por ejemplo nombre@gmail.com).');
  end if;

  if p_id is null then
    if not exists (select 1 from public.escuelas where id = p_escuela_id) then
      return jsonb_build_object('error', 'No encontramos esa escuela.');
    end if;
    insert into public.contactos_escuela (escuela_id, nombre, cargo, celular, correo, origen, actualizado_por)
    values (p_escuela_id, v_nombre, v_cargo, v_celular, v_correo, 'panel', (select auth.uid()))
    returning * into v_fila;
  else
    -- Corregido desde el panel deja de ser «de la planilla»: volver a
    -- cargarla no pisa la corrección
    update public.contactos_escuela
       set nombre = v_nombre, cargo = v_cargo, celular = v_celular, correo = v_correo,
           origen = 'panel', actualizado_por = (select auth.uid()), actualizado_en = now()
     where id = p_id
    returning * into v_fila;
    if not found then
      return jsonb_build_object('error', 'Ese contacto ya no está: puede que alguien lo haya quitado. Volvé a abrir la escuela.');
    end if;
  end if;
  return to_jsonb(v_fila);
end;
$$;

create or replace function public.quitar_contacto(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.es_equipo() then
    return jsonb_build_object('error', 'Tu usuario no puede cambiar contactos.');
  end if;
  delete from public.contactos_escuela where id = p_id;
  return jsonb_build_object('ok', true);
end;
$$;

revoke execute on function public.guardar_contacto(bigint, text, text, text, text, text) from public, anon;
revoke execute on function public.quitar_contacto(bigint) from public, anon;
grant  execute on function public.guardar_contacto(bigint, text, text, text, text, text) to authenticated;
grant  execute on function public.quitar_contacto(bigint) to authenticated;
