-- Lo que no está en el JSON (alta desde el panel): al final de su trimestre,
-- en el orden que tenía. Lo del JSON no se renumera: si algo se archivó queda
-- un hueco, y está bien, porque el orden solo se compara dentro del trimestre.
with fuera as (
  select s.id, e.espacio_id, s.anio, s.trimestre,
         row_number() over (partition by e.espacio_id, s.anio, s.trimestre order by s.orden, s.id) as n
    from public.saberes s
    join public.ejes e on e.id = s.eje_id
   where s.estado = 'activo' and s.id not in (select id from orden_nuevo)
),
tope as (
  select e.espacio_id, s.anio, s.trimestre, max(s.orden) as ultimo
    from public.saberes s
    join public.ejes e on e.id = s.eje_id
   where s.id in (select id from orden_nuevo)
   group by e.espacio_id, s.anio, s.trimestre
)
update public.saberes s
   set orden = coalesce(t.ultimo, 0) + f.n
  from fuera f
  left join tope t on t.espacio_id = f.espacio_id and t.anio is not distinct from f.anio
                  and t.trimestre = f.trimestre
 where s.id = f.id and s.orden <> coalesce(t.ultimo, 0) + f.n;

